#!/usr/bin/env node
// ── Manifest baking ───────────────────────────────────────────────────────
// Turns the dev server's dynamic listing routes into static JSON, so the same client
// works on a host with no server at all. This is 2.5.0's build-manifests.js pattern
// (§8.10), and it is why the client never needs to know where it is running.
//
//   node scripts/build-manifests.js            # bake what's committed (for GitHub Pages)
//   node scripts/build-manifests.js --all      # bake everything on disk (local)
//
// The default is deliberately the PUBLIC set. Show assets are gitignored because shows
// are performed locally, so baking everything would produce a manifest full of files
// that GitHub Pages doesn't have — the page would then 404 its way through a show.

import fs from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ASSET_EXT = /\.(png|jpe?g|gif|webp|svg|mp4|webm|mov|mp3|wav|ogg|m4a)$/i;
// Textures are referenced by PATH, not by number — and numbering them would be actively
// harmful: `lined_paper2.jpeg` parses to asset 2 and would collide with real art.
const UNNUMBERED = ['textures/'];
const all = process.argv.includes('--all');

// Only assets/demo/ is committed (see .gitignore), so that is the public set.
const PUBLIC_DIRS = ['demo'];

async function walk(dir, base = '') {
  const out = [];
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...(await walk(path.join(dir, e.name), rel)));
    else if (ASSET_EXT.test(e.name)) out.push(rel);
  }
  return out;
}

// Paths git tracks under assets/, relative to assets/ — or null if git cannot answer.
function gitTracked(assetsDir) {
  try {
    const out = execFileSync('git', ['ls-files', '-z', '--', assetsDir], { cwd: ROOT });
    return new Set(
      out.toString('utf8').split('\0').filter(Boolean)
        .map((f) => path.relative('assets', f)));
  } catch {
    return null;
  }
}

async function main() {
  const assetsDir = path.join(ROOT, 'assets');
  let files = (await walk(assetsDir)).sort()
    .filter((f) => !UNNUMBERED.some((d) => f.startsWith(d)));
  if (!all) {
    files = files.filter((f) => PUBLIC_DIRS.some((d) => f.startsWith(`${d}/`)));
    // ...and then only what git ACTUALLY TRACKS. Walking the disk is not the same as
    // knowing what GitHub Pages will have: a file that is on disk but gitignored (the
    // 2.6MB demo mp3) would be advertised in the manifest and 404 for every visitor.
    // Asking git makes "public set" mean literally "what is committed".
    const tracked = gitTracked(assetsDir);
    if (tracked) {
      const before = files.length;
      files = files.filter((f) => tracked.has(f));
      const dropped = before - files.length;
      if (dropped) console.log(`  (${dropped} on-disk asset(s) omitted — not tracked by git)`);
    } else {
      console.warn('  ! git unavailable — manifest lists what is on disk, which may 404 publicly');
    }
  }

  // Warn about anything the number-keyed addressing cannot see. Silent drops here
  // become a scene that renders nothing, hours later.
  const seen = new Map();
  for (const f of files) {
    const m = path.basename(f).match(/(\d+)/);
    if (!m) { console.warn(`  ! "${f}" has no number in its name — it will not be addressable by id`); continue; }
    const n = parseInt(m[1], 10);
    if (seen.has(n)) console.warn(`  ! duplicate asset number ${n}: "${seen.get(n)}" and "${f}"`);
    else seen.set(n, f);
  }

  const manifest = {
    _note: 'Generated by scripts/build-manifests.js. Assets are keyed by the number in the filename, not by position in this list. Locally the dev server serves this path dynamically instead.',
    base: './assets/',
    files,
  };
  const out = path.join(assetsDir, 'manifest.json');
  await fs.writeFile(out, JSON.stringify(manifest, null, 2) + '\n', 'utf8');
  console.log(`assets/manifest.json — ${files.length} file(s)${all ? ' (all on disk)' : ' (public set)'}`);

  // A listing of shows, for a future directory page. Scripts and configs are committed,
  // so this one is the same locally and statically.
  const showsDir = path.join(ROOT, 'shows');
  const shows = [];
  for (const e of await fs.readdir(showsDir, { withFileTypes: true }).catch(() => [])) {
    if (!e.isDirectory()) continue;
    const config = await fs.readFile(path.join(showsDir, e.name, 'config.json'), 'utf8')
      .then(JSON.parse).catch(() => ({}));
    const script = await fs.readFile(path.join(showsDir, e.name, 'script.json'), 'utf8')
      .then(JSON.parse).catch(() => null);
    if (!script) { console.warn(`  ! shows/${e.name} has no script.json — skipped`); continue; }
    shows.push({ name: e.name, title: config.title ?? e.name, scenes: script.length });
  }
  await fs.writeFile(path.join(showsDir, 'index.json'), JSON.stringify({ shows }, null, 2) + '\n', 'utf8');
  console.log(`shows/index.json — ${shows.length} show(s)`);
}

main().catch((err) => { console.error(err); process.exit(1); });
